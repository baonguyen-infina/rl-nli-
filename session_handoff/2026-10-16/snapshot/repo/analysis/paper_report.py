"""Generate the native-allocation paper exclusively from verified test artifacts."""
import argparse
from pathlib import Path
from analysis.collect import collect_runs
from analysis.stats import paired_cluster_macro_f1_bootstrap
from common.io import ROOT, RESULTS, read_jsonl, write_json

MAIN = {
    'HD3R9L': 'SFT',
    'HN1R9L': 'Ordinary GRPO + CE',
    'HN0R11L': 'Allocation, no policy loss',
    'HN4R9L': 'Native direct + GRPO',
    'HN5R10L': 'Native log-$Q$ + GRPO',
    'HN6R11L': 'Native bounded-$Q$ + GRPO',
}
MECHANISM = {'HN6R11P200L': 'Native groups', 'HN7R12P200L': 'Random groups'}
SECONDARY = {key[:-1]+'C': value for key,value in MAIN.items()}
SCOPES = {'main': MAIN, 'mechanism': MECHANISM, 'secondary': SECONDARY}


def render_comparison(rows, scope):
    """Every input has test provenance; scope determines one inference format."""
    if scope not in SCOPES:
        raise ValueError('Unknown comparison scope')
    known = {**MAIN, **MECHANISM, **SECONDARY}
    seen = set()
    for row in rows:
        rid = row.get('run_id')
        if row.get('split') != 'test' or rid not in known:
            raise ValueError('Registered held-out test rows required')
        fmt = 'cot' if rid in SECONDARY else 'label'
        if row.get('format') != fmt or row.get('seed') != 0:
            raise ValueError('Wrong format or seed for the registered view')
        if rid in seen:
            raise ValueError('Duplicate test view')
        seen.add(rid)
    selected = {row['run_id']: row for row in rows if row['run_id'] in SCOPES[scope]}
    if not selected:
        raise ValueError('No completed test rows for this comparison')
    lines = [r'% Generated by analysis.paper_report; split=test; training seed=0.',
             r'\begin{tabular}{lrrr}', r'\toprule',
             r'Method & MF1 & Acc. & Parse \\', r'\midrule']
    for rid, name in SCOPES[scope].items():
        if rid in selected:
            row = selected[rid]
            values = [f'{100*row[key]:.2f}' for key in ('macro_f1','accuracy','parse_rate')]
            lines.append(name+' & '+' & '.join(values)+r' \\')
    return '\n'.join(lines+[r'\bottomrule',r'\end{tabular}'])+'\n'


def compare_predictions(a, b, n_boot=10000):
    """Align by ID, then use the UID's premise identifier only for analysis."""
    from data.prepare import parse_uid
    def indexed(rows):
        result = {row['id']: row for row in rows}
        if len(result) != len(rows):
            raise ValueError('Duplicate prediction ID')
        return result
    left, right = indexed(a), indexed(b)
    if set(left) != set(right):
        raise ValueError('Paired test predictions have different IDs')
    ids = sorted(left)
    if any(left[i]['gold'] != right[i]['gold'] for i in ids):
        raise ValueError('Paired test gold labels differ')
    out = paired_cluster_macro_f1_bootstrap(
        [left[i]['gold'] for i in ids], [left[i]['pred'] for i in ids],
        [right[i]['pred'] for i in ids], [parse_uid(i)['premise_id'] for i in ids],
        n_boot=n_boot, seed=0)
    return {**out, 'n': len(ids), 'interval_scope': 'conditional_on_fitted_models'}


def build_report(rows, paper_dir, *, n_boot=10000):
    """Recompute metrics from immutable predictions before writing any score."""
    from eval.metrics import compute_metrics
    paper_dir = Path(paper_dir)
    tables = paper_dir/'tables'; tables.mkdir(parents=True,exist_ok=True)
    predictions = {}
    for row in rows:
        records = read_jsonl(Path(row['source'])/'predictions_test.jsonl')
        actual = compute_metrics(records)
        for key in ('n','macro_f1','accuracy','parse_rate'):
            if abs(actual[key]-row[key]) > 1e-12:
                raise ValueError('Stored metric disagrees with test predictions')
        predictions[row['run_id']] = records
    # Validate provenance and identities even when a row belongs to another scope.
    (tables/'results_test.tex').write_text(render_comparison(rows,'main'))
    for scope,filename,caption in (
        ('mechanism','ablation_test.tex',
         'Grouping control at fixed update 200, with the same 400-update learning-rate horizon. Held-out test percentages; label-only inference.'),
        ('secondary','secondary_test.tex',
         'Secondary bounded-reasoning inference on the same fitted adapters. Held-out test percentages; this format is reported separately.')):
        if any(row['run_id'] in SCOPES[scope] for row in rows):
            table=render_comparison(rows,scope)
            (tables/filename).write_text('\\begin{table}[t]\n\\centering\\small\n\\setlength{\\tabcolsep}{3pt}\n'+table+
                '\\caption{'+caption+'}\n\\end{table}\n')
    paired = {}
    comparisons = [('HN6R11L','HN1R9L'), ('HN4R9L','HN1R9L'),
                   ('HN6R11L','HN0R11L'), ('HN6R11L','HD3R9L'),
                   ('HN6R11P200L','HN7R12P200L')]
    for left,right in comparisons:
        if left in predictions and right in predictions:
            paired[left+'__'+right] = compare_predictions(predictions[left],predictions[right],n_boot)
    write_json(tables/'paired_test_intervals.json',paired)
    by_id = {row['run_id']: row for row in rows}
    key='HN6R11L__HN1R9L'
    if key in paired:
        interval=paired[key];method=100*by_id['HN6R11L']['macro_f1'];control=100*by_id['HN1R9L']['macro_f1']
        delta=100*interval['diff'];low=100*interval['ci_low'];high=100*interval['ci_high']
        (tables/'abstract_results.tex').write_text(
            f'On held-out ViANLI, bounded native allocation obtains {method:.2f} Macro-F1, '
            f'compared with {control:.2f} for matched ordinary GRPO with answer supervision '
            f'(difference {delta:+.2f} points).\n')
        interpretation = ('The interval includes zero, so this comparison does not establish an advantage.'
            if low<=0<=high else 'The interval excludes zero conditional on these fitted models; it does not resolve training-seed variability.')
        discussion=(f'The bounded native method reaches {method:.2f} test Macro-F1 versus '
            f'{control:.2f} for matched ordinary GRPO with answer cross-entropy. '
            f'The difference is {delta:+.2f} percentage points, with an unadjusted 95\\% paired '
            f'premise-cluster bootstrap interval of [{low:+.2f}, {high:+.2f}] '
            f'({interval["n_clusters"]} premise clusters; {n_boot:,} resamples). '
            +interpretation+' These descriptive intervals do not account for the exploratory development search.\n')
        if 'HN6R11L__HN0R11L' in paired:
            result=paired['HN6R11L__HN0R11L']
            discussion+=(f'Against the no-policy allocation control, the difference is '
                f'{100*result["diff"]:+.2f} points, with interval '
                f'[{100*result["ci_low"]:+.2f}, {100*result["ci_high"]:+.2f}]. '
                'This contrast changes the complete policy/KL term and therefore does not isolate the bounded bonus alone.\n')
        (tables/'test_discussion.tex').write_text(discussion)
        paragraphs=[]
        native=['HN4R9L','HN5R10L','HN6R11L']
        if all(rid in by_id for rid in native) and all(
                by_id[rid]['macro_f1']<=by_id['HN1R9L']['macro_f1'] for rid in native):
            paragraphs.append('None of the native-allocation variants improves the primary-view '
                'point estimate over matched ordinary GRPO. The held-out results therefore do not '
                'establish the proposed native supervision as a classification improvement.')
        group_key='HN6R11P200L__HN7R12P200L'
        if group_key in paired:
            result=paired[group_key]
            paragraphs.append(f'At fixed update 200, native groups reach '
                f'{100*by_id["HN6R11P200L"]["macro_f1"]:.2f} Macro-F1, compared with '
                f'{100*by_id["HN7R12P200L"]["macro_f1"]:.2f} for matched random groups. '
                f'The native-minus-random difference is {100*result["diff"]:+.2f} points '
                f'(interval [{100*result["ci_low"]:+.2f}, {100*result["ci_high"]:+.2f}]). '
                'The shared-premise grouping hypothesis is not supported by a positive point estimate '
                'in this comparison; the interval also does not establish a reliable ordering.')
        if 'HN0R11C' in by_id and 'HN6R11C' in by_id:
            paragraphs.append(f'Under the separate bounded-reasoning view, the no-policy control '
                f'achieves {100*by_id["HN0R11C"]["macro_f1"]:.2f} Macro-F1, versus '
                f'{100*by_id["HN6R11C"]["macro_f1"]:.2f} for bounded native GRPO. '
                'The point estimate does not identify an advantage from retaining the complete '
                'policy/KL term. Additional answer supervision and allocation training remain '
                'alternative explanations for improvement over the reasoning-view SFT reference.')
        (tables/'interpretation_test.tex').write_text('\n\n'.join(paragraphs)+'\n')
        conclusion=('Under the registered held-out protocol, these single-seed comparisons do not establish '
            'a classification benefit from the proposed bounded native objective over matched ordinary RL. '
            'The grouping and no-policy controls constrain the mechanistic interpretation. '
            'The objective remains a testable supervision design, rather than an established performance improvement.'
            if interval['ci_low']<=0 else
            'The held-out comparison supports a conditional improvement for the fitted bounded-native adapter '
            'over the ordinary-RL control. Replication across training seeds and benchmarks remains necessary, '
            'and the mechanism controls must be interpreted separately.')
        (tables/'conclusion_test.tex').write_text(conclusion+'\n')
    write_json(tables/'test_report_provenance.json',{
        'split':'test','training_seeds':[0], 'generator':'analysis.paper_report',
        'runs':[{key:row[key] for key in ('run_id','seed','format','source','n')} for row in rows],
        'paired_uncertainty':'premise_cluster_conditional_on_fitted_models'})
    return paired


def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--runs',nargs='+',required=True)
    ap.add_argument('--results',type=Path,default=RESULTS)
    ap.add_argument('--paper-dir',type=Path,default=ROOT/'paper')
    ap.add_argument('--n-boot',type=int,default=10000)
    args=ap.parse_args()
    rows=[row for row in collect_runs(args.results,split='test') if row['run_id'] in args.runs]
    if set(args.runs)!={row['run_id'] for row in rows}:
        raise ValueError('Registered cohort has missing completed test results')
    build_report(rows,args.paper_dir,n_boot=args.n_boot)
    print({'test_runs':len(rows),'paper_dir':str(args.paper_dir)})


if __name__=='__main__':main()
