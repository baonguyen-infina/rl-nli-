"""Generate an ACL results table from completed held-out test artifacts only."""
import argparse
from pathlib import Path
from statistics import mean,stdev
from analysis.collect import collect_runs
from common.io import ROOT


def escape(text):
    return str(text).replace('_',r'\_').replace('%',r'\%').replace('&',r'\&')


def render(rows,split='test'):
    if split!='test' or any(row.get('split')!='test' for row in rows):
        raise ValueError('Paper results require split=test on every recorded row')
    if not rows:
        raise ValueError('No completed test results; keep the paper results pending')
    lines=[r'% Generated by analysis.make_tables; split=test; no manually copied scores.',r'\begin{tabular}{lrrrr}',r'\toprule',r'Run & Seeds & Macro-F1 & Accuracy & Parse \\',r'\midrule']
    keys=sorted({r['run_id'] for r in rows})
    for key in keys:
        group=[r for r in rows if r['run_id']==key]
        values=[]
        for metric in ['macro_f1','accuracy','parse_rate']:
            v=[100*r[metric] for r in group]
            values.append(f'{mean(v):.2f}' + (f' $\\pm$ {stdev(v):.2f}' if len(v)>1 else ''))
        lines.append(escape(key)+' & '+str(len(group))+' & '+' & '.join(values)+r' \\')
    lines += [r'\bottomrule',r'\end{tabular}']
    return '\n'.join(lines)+'\n'


def main():
    ap=argparse.ArgumentParser();ap.add_argument('--split',choices=['test'],default='test')
    ap.add_argument('--runs',nargs='*');a=ap.parse_args()
    rows=collect_runs(split=a.split)
    if a.runs:rows=[r for r in rows if r['run_id'] in a.runs]
    try:table=render(rows,a.split)
    except ValueError as exc:ap.error(str(exc))
    out=ROOT/'paper'/'tables'/'results_test.tex';out.parent.mkdir(parents=True,exist_ok=True)
    out.write_text(table);print(out)

if __name__=='__main__':main()
